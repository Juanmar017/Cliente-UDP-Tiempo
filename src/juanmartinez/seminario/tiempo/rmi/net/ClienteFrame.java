    private void btnConvertir2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConvertir2ActionPerformed
        try {
            // 1. Leer los campos de texto
            int horas = Integer.parseInt(txtHoras.getText().trim());
            int minutos = Integer.parseInt(txtMinutos.getText().trim());
            int segundos = Integer.parseInt(txtSegundos.getText().trim());

            // 2. Formatear el mensaje en texto plano separado por comas
            String mensaje = horas + "," + minutos + "," + segundos;
            byte[] bufferEnvio = mensaje.getBytes();

            // 3. Crear el socket UDP del lado del cliente
            java.net.DatagramSocket socketUdp = new java.net.DatagramSocket();
            java.net.InetAddress servidorIP = java.net.InetAddress.getByName("localhost");
            int puertoServidor = 9876;

            // 4. Enviar el paquete al servidor
            java.net.DatagramPacket paqueteEnvio = new java.net.DatagramPacket(
                bufferEnvio, bufferEnvio.length, servidorIP, puertoServidor
            );
            socketUdp.send(paqueteEnvio);

            // 5. Recibir la respuesta del servidor
            byte[] bufferRecepcion = new byte[1024];
            java.net.DatagramPacket paqueteRecepcion = new java.net.DatagramPacket(bufferRecepcion, bufferRecepcion.length);
            socketUdp.receive(paqueteRecepcion); // Se queda esperando la respuesta

            // 6. Mostrar el resultado en el JLabel
            String resultadoStr = new String(paqueteRecepcion.getData(), 0, paqueteRecepcion.getLength());
            lblResultado.setText("Total en segundos: " + resultadoStr + " seg.");

            // 7. Cerrar el socket del cliente
            socketUdp.close();

        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Por favor ingrese números enteros válidos.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        } catch (Exception ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error de red UDP: " + ex.getMessage(), "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnConvertir2ActionPerformed

